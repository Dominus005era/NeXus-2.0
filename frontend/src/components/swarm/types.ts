export interface DynamicPipelineStep {
  id: string;
  sourceId: string;
  targetId: string;
  label: string;
  color: string;
  stepType: 'dispatch' | 'decompose' | 'consult' | 'peer_consult' | 'solve' | 'deliver';
  sourceThought?: string;
  targetThought: string;
  telemetryBadge?: string;
}

